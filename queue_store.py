from datetime import date, datetime, timezone
import json
import os
import threading
from zoneinfo import ZoneInfo

import psycopg
from psycopg.rows import dict_row


BASE_DIR = os.path.dirname(os.path.abspath(__file__))
APP_TIMEZONE = ZoneInfo(os.getenv("APP_TIMEZONE", "Asia/Kolkata"))
QC_DISPOSITIONS = ("Scrap", "Return to vendor", "Rework", "Use as it is")
# ponytail: one process-wide lock serialises writes for the single-worker
# gunicorn setup (workers=1). If this ever runs multiple workers/processes,
# drop the lock and lean on the Postgres unique constraints + row locks.
_queue_lock = threading.Lock()
_schema_lock = threading.Lock()
_schema_ready = False


def current_work_date() -> str:
    return datetime.now(APP_TIMEZONE).date().isoformat()


def _work_date(value: str | None = None) -> str:
    candidate = str(value or current_work_date()).strip()
    try:
        return date.fromisoformat(candidate).isoformat()
    except ValueError as exc:
        raise ValueError("work_date must use YYYY-MM-DD.") from exc


def _database_url() -> str:
    # Local development fallback only. Every deployment sets DATABASE_URL
    # (docker-compose.yml points it at this service's own db container).
    return os.getenv(
        "DATABASE_URL",
        "postgresql://modula:modula@localhost:5432/modula_planner",
    )


def _connect() -> psycopg.Connection:
    # psycopg3 connections are context managers: the `with` block commits on
    # success / rolls back on error, then closes — same shape as the old sqlite
    # `with closing(conn), conn:` pattern.
    return psycopg.connect(_database_url(), row_factory=dict_row)


def _ensure_schema() -> None:
    """Create tables once per process, in their own committed transaction so
    the ready-flag only flips after the DDL is durable. Always called while
    holding _queue_lock (or before any connection), so the check is race-free."""
    global _schema_ready
    if _schema_ready:
        return
    with _schema_lock:
        if _schema_ready:
            return
        with _connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS printed_parts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    po_number TEXT NOT NULL DEFAULT '',
                    part_code TEXT NOT NULL,
                    quantity INTEGER NOT NULL,
                    status TEXT NOT NULL DEFAULT 'queued',
                    so_number TEXT NOT NULL DEFAULT '',
                    planner_plan_id TEXT NOT NULL DEFAULT '',
                    work_date TEXT,
                    created_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS shift_plans (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    work_date TEXT NOT NULL,
                    po_number TEXT NOT NULL,
                    label_filename TEXT NOT NULL,
                    label_pdf BYTEA NOT NULL,
                    created_at TEXT NOT NULL,
                    UNIQUE (work_date, po_number)
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS production_events (
                    event_id TEXT PRIMARY KEY,
                    action TEXT NOT NULL,
                    po_number TEXT NOT NULL,
                    so_number TEXT NOT NULL,
                    part_code TEXT NOT NULL,
                    quantity INTEGER NOT NULL,
                    work_date TEXT NOT NULL,
                    target_row_id BIGINT,
                    planner_plan_id TEXT NOT NULL DEFAULT '',
                    status TEXT NOT NULL DEFAULT 'pending',
                    error TEXT,
                    planner_response TEXT,
                    problem_description TEXT NOT NULL DEFAULT '',
                    disposition TEXT NOT NULL DEFAULT '',
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                "ALTER TABLE production_events "
                "ADD COLUMN IF NOT EXISTS problem_description TEXT NOT NULL DEFAULT ''"
            )
            connection.execute(
                "ALTER TABLE production_events "
                "ADD COLUMN IF NOT EXISTS disposition TEXT NOT NULL DEFAULT ''"
            )
            # Retry bookkeeping: how often Planner was tried, and the HTTP
            # status of its last answer (NULL = never answered).
            connection.execute(
                "ALTER TABLE production_events "
                "ADD COLUMN IF NOT EXISTS attempts INTEGER NOT NULL DEFAULT 0"
            )
            connection.execute(
                "ALTER TABLE production_events "
                "ADD COLUMN IF NOT EXISTS error_status INTEGER"
            )
        _schema_ready = True


def _part_qty(part_code: str, quantity: int) -> tuple[str, int]:
    code = str(part_code or "").strip().upper()
    try:
        qty = int(quantity)
    except (TypeError, ValueError, OverflowError):
        qty = 0
    if not code:
        raise ValueError("part_code is required.")
    if isinstance(quantity, bool) or str(quantity).strip() != str(qty) or qty < 1 or qty > 500:
        raise ValueError("quantity must be between 1 and 500.")
    return code, qty


def _po_number(value: str) -> str:
    po_number = str(value or "").strip().upper()
    if not po_number:
        raise ValueError("po_number is required.")
    return po_number


def _so_number(value: str) -> str:
    so_number = str(value or "").strip().upper()
    if not so_number:
        raise ValueError("so_number is required.")
    return so_number


def _event_id(value: str) -> str:
    event_id = str(value or "").strip()
    if len(event_id) < 8 or len(event_id) > 200:
        raise ValueError("event_id must be between 8 and 200 characters.")
    return event_id


def _qc_details(problem_description: str, disposition: str) -> tuple[str, str]:
    description = str(problem_description or "").strip()
    selected_disposition = str(disposition or "").strip()
    if not description:
        raise ValueError("problem_description is required.")
    if len(description) > 300:
        raise ValueError("problem_description must be 300 characters or fewer.")
    if selected_disposition not in QC_DISPOSITIONS:
        raise ValueError(
            "disposition must be one of: " + ", ".join(QC_DISPOSITIONS) + "."
        )
    return description, selected_disposition


def get_printed_part(row_id: int) -> dict:
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        row = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s",
            (row_id,),
        ).fetchone()
    if not row:
        raise ValueError("Queue row was not found.")
    return dict(row)


def stage_production_event(
    event_id: str,
    action: str,
    po_number: str,
    so_number: str,
    part_code: str,
    quantity: int,
    work_date: str,
    *,
    planner_plan_id: str = "",
    target_row_id: int | None = None,
    problem_description: str = "",
    disposition: str = "",
) -> dict:
    event = _event_id(event_id)
    if action not in {"produced", "rejected"}:
        raise ValueError("action must be produced or rejected.")
    code, qty = _part_qty(part_code, quantity)
    po = _po_number(po_number)
    so = _so_number(so_number) if action == "rejected" else str(so_number or "").strip().upper()
    description, selected_disposition = (
        _qc_details(problem_description, disposition)
        if action == "rejected"
        else ("", "")
    )
    if not str(work_date or "").strip():
        raise ValueError("work_date is required.")
    work_date = _work_date(work_date)
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        existing = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s",
            (event,),
        ).fetchone()
        if existing:
            expected = (
                action,
                po,
                so,
                code,
                qty,
                work_date,
                target_row_id,
                description,
                selected_disposition,
            )
            actual = (
                existing["action"],
                existing["po_number"],
                existing["so_number"],
                existing["part_code"],
                existing["quantity"],
                existing["work_date"],
                existing["target_row_id"] if action == "rejected" else None,
                existing["problem_description"],
                existing["disposition"],
            )
            if actual != expected:
                raise ValueError("event_id was already used with different production data.")
            return dict(existing)
        if action == "rejected":
            row = connection.execute(
                "SELECT * FROM printed_parts WHERE id = %s AND work_date = %s",
                (target_row_id, work_date),
            ).fetchone()
            if not row or row["status"] != "synced" or int(row["quantity"]) < qty:
                raise ValueError("Rejected quantity exceeds the synced panel quantity.")
        connection.execute(
            """
            INSERT INTO production_events
                (event_id, action, po_number, so_number, part_code, quantity,
                 work_date, target_row_id, planner_plan_id, problem_description,
                 disposition, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            (
                event,
                action,
                po,
                so,
                code,
                qty,
                work_date,
                target_row_id,
                str(planner_plan_id or "").strip(),
                description,
                selected_disposition,
                now,
                now,
            ),
        )
        row = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s",
            (event,),
        ).fetchone()
    return dict(row)


def fail_production_event(
    event_id: str, error: str, status_code: int | None = None
) -> None:
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        connection.execute(
            """
            UPDATE production_events
            SET status = 'error', error = %s, error_status = %s,
                attempts = attempts + 1, updated_at = %s
            WHERE event_id = %s AND status NOT IN ('synced', 'cancelled')
            """,
            (
                str(error or "Planner sync failed.")[:1000],
                status_code,
                datetime.now(timezone.utc).isoformat(timespec="seconds"),
                event_id,
            ),
        )


def record_local_production_event(event_id: str, error: str) -> dict:
    """Keep a produced barcode locally when Planner did not accept it."""
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        event = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s FOR UPDATE",
            (event_id,),
        ).fetchone()
        if not event or event["action"] != "produced":
            raise ValueError("Production event was not found.")
        if event["status"] == "synced":
            raise ValueError("That event is already synced with Planner.")

        row = (
            connection.execute(
                "SELECT * FROM printed_parts WHERE id = %s",
                (event["target_row_id"],),
            ).fetchone()
            if event["target_row_id"]
            else None
        )
        if not row:
            row = connection.execute(
                """
                INSERT INTO printed_parts
                    (po_number, part_code, quantity, status, work_date, created_at)
                VALUES (%s, %s, %s, 'error', %s, %s)
                RETURNING *
                """,
                (
                    event["po_number"],
                    event["part_code"],
                    event["quantity"],
                    event["work_date"],
                    now,
                ),
            ).fetchone()

        connection.execute(
            """
            UPDATE production_events
            SET target_row_id = %s, status = 'error', error = %s, updated_at = %s
            WHERE event_id = %s
            """,
            (
                row["id"],
                str(error or "Planner sync failed.")[:1000],
                now,
                event_id,
            ),
        )
    return dict(row)


def skip_production_event(event_id: str, error: str) -> dict | None:
    """Keep fulfilled Planner production local without retrying or double-counting."""
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        event = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s FOR UPDATE",
            (event_id,),
        ).fetchone()
        if not event:
            raise ValueError("Production event was not found.")
        if event["status"] == "synced":
            raise ValueError("That event is already synced with Planner.")
        if event["status"] == "skipped":
            row = connection.execute(
                "SELECT * FROM printed_parts WHERE id = %s",
                (event["target_row_id"],),
            ).fetchone()
            return dict(row) if row else None
        if event["action"] != "produced":
            raise ValueError("Only production events can be kept local.")

        # A failed sync already put this event's quantity in its own 'error'
        # row; keep that row instead of adding the quantity a second time.
        own_row = (
            connection.execute(
                """
                UPDATE printed_parts SET status = 'queued'
                WHERE id = %s AND status = 'error'
                RETURNING *
                """,
                (event["target_row_id"],),
            ).fetchone()
            if event["target_row_id"]
            else None
        )
        row = own_row or connection.execute(
            """
            SELECT * FROM printed_parts
            WHERE work_date = %s AND po_number = %s AND part_code = %s
              AND status = 'queued'
            ORDER BY id DESC LIMIT 1 FOR UPDATE
            """,
            (event["work_date"], event["po_number"], event["part_code"]),
        ).fetchone()
        if own_row:
            pass
        elif row:
            quantity = int(row["quantity"]) + int(event["quantity"])
            if quantity > 500:
                raise ValueError("quantity must be between 1 and 500.")
            row = connection.execute(
                """
                UPDATE printed_parts
                SET quantity = %s, status = 'queued'
                WHERE id = %s
                RETURNING *
                """,
                (quantity, row["id"]),
            ).fetchone()
        else:
            row = connection.execute(
                """
                INSERT INTO printed_parts
                    (po_number, part_code, quantity, status, work_date, created_at)
                VALUES (%s, %s, %s, 'queued', %s, %s)
                RETURNING *
                """,
                (
                    event["po_number"],
                    event["part_code"],
                    event["quantity"],
                    event["work_date"],
                    now,
                ),
            ).fetchone()
        connection.execute(
            """
            UPDATE production_events
            SET status = 'skipped', error = %s, target_row_id = %s, updated_at = %s
            WHERE event_id = %s
            """,
            (
                str(error or "Planner quantity is already fulfilled.")[:1000],
                row["id"],
                now,
                event_id,
            ),
        )
    return dict(row)


def complete_production_event(event_id: str, planner_response: dict) -> dict | None:
    plan_id = str(planner_response.get("planId") or "").strip()
    if not plan_id:
        raise ValueError("Planner response did not include planId.")
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        event = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s",
            (event_id,),
        ).fetchone()
        if not event:
            raise ValueError("Production event was not found.")
        if event["status"] == "synced":
            row = connection.execute(
                "SELECT * FROM printed_parts WHERE id = %s",
                (event["target_row_id"],),
            ).fetchone()
            return dict(row) if row else None

        if event["action"] == "produced":
            allocations = planner_response.get("allocations") or [
                {
                    "soNumber": planner_response.get("soNumber"),
                    "quantity": event["quantity"],
                }
            ]
            normalized_allocations = [
                (_so_number(item.get("soNumber")), int(item.get("quantity") or 0))
                for item in allocations
            ]
            # Planner may take only part of a print when the PO is nearly
            # fulfilled; the rest ("overflow") stays in the queue as local.
            try:
                overflow = int(planner_response.get("overflow") or 0)
            except (TypeError, ValueError):
                overflow = -1
            if (
                overflow < 0
                or any(quantity <= 0 for _, quantity in normalized_allocations)
                or sum(quantity for _, quantity in normalized_allocations) + overflow
                != int(event["quantity"])
            ):
                raise ValueError("Planner response included invalid SO allocations.")
            if event["status"] == "error" and event["target_row_id"]:
                connection.execute(
                    """
                    DELETE FROM printed_parts
                    WHERE id = %s AND status = 'error'
                    """,
                    (event["target_row_id"],),
                )
            row_ids = []
            for so_number, quantity in normalized_allocations:
                row = connection.execute(
                    """
                    SELECT * FROM printed_parts
                    WHERE work_date = %s AND po_number = %s AND so_number = %s
                      AND part_code = %s AND planner_plan_id = %s AND status = 'synced'
                    ORDER BY id DESC LIMIT 1
                    """,
                    (
                        event["work_date"],
                        event["po_number"],
                        so_number,
                        event["part_code"],
                        plan_id,
                    ),
                ).fetchone()
                if row:
                    connection.execute(
                        "UPDATE printed_parts SET quantity = quantity + %s WHERE id = %s",
                        (quantity, row["id"]),
                    )
                    row_ids.append(row["id"])
                else:
                    inserted = connection.execute(
                        """
                        INSERT INTO printed_parts
                            (po_number, so_number, part_code, quantity, status,
                             planner_plan_id, work_date, created_at)
                        VALUES (%s, %s, %s, %s, 'synced', %s, %s, %s)
                        RETURNING id
                        """,
                        (
                            event["po_number"],
                            so_number,
                            event["part_code"],
                            quantity,
                            plan_id,
                            event["work_date"],
                            now,
                        ),
                    ).fetchone()
                    row_ids.append(inserted["id"])
            row_id = row_ids[0]
            if overflow:
                connection.execute(
                    """
                    INSERT INTO printed_parts
                        (po_number, part_code, quantity, status, work_date, created_at)
                    VALUES (%s, %s, %s, 'queued', %s, %s)
                    """,
                    (
                        event["po_number"],
                        event["part_code"],
                        overflow,
                        event["work_date"],
                        now,
                    ),
                )
            connection.execute(
                "UPDATE production_events SET target_row_id = %s WHERE event_id = %s",
                (row_id, event_id),
            )
        else:
            row_id = event["target_row_id"]
            row = connection.execute(
                "SELECT quantity FROM printed_parts WHERE id = %s",
                (row_id,),
            ).fetchone()
            if not row or int(row["quantity"]) < int(event["quantity"]):
                raise ValueError("Rejected quantity exceeds the synced panel quantity.")
            connection.execute(
                "UPDATE printed_parts SET quantity = quantity - %s WHERE id = %s",
                (event["quantity"], row_id),
            )

        connection.execute(
            """
            UPDATE production_events
            SET planner_plan_id = %s, status = 'synced', error = NULL,
                planner_response = %s, updated_at = %s
            WHERE event_id = %s
            """,
            (plan_id, json.dumps(planner_response), now, event_id),
        )
        row = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s AND quantity > 0",
            (row_id,),
        ).fetchone()
    return dict(row) if row else None


def add_printed_part(
    part_code: str,
    quantity: int = 1,
    po_number: str = "",
    work_date: str | None = None,
) -> dict:
    code, qty = _part_qty(part_code, quantity)
    po = _po_number(po_number)
    work_date = _work_date(work_date)
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        existing = connection.execute(
            """
            SELECT * FROM printed_parts
            WHERE work_date = %s AND po_number = %s AND part_code = %s
              AND status = 'queued'
            ORDER BY id DESC LIMIT 1
            """,
            (work_date, po, code),
        ).fetchone()
        if existing:
            new_quantity = int(existing["quantity"]) + qty
            if new_quantity > 500:
                raise ValueError("quantity must be between 1 and 500.")
            connection.execute(
                "UPDATE printed_parts SET quantity = %s, status = 'queued' WHERE id = %s",
                (new_quantity, existing["id"]),
            )
            row_id = existing["id"]
        else:
            inserted = connection.execute(
                """
                INSERT INTO printed_parts
                    (po_number, part_code, quantity, work_date, created_at)
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    po,
                    code,
                    qty,
                    work_date,
                    datetime.now(timezone.utc).isoformat(timespec="seconds"),
                ),
            ).fetchone()
            row_id = inserted["id"]
        row = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s",
            (row_id,),
        ).fetchone()
    return dict(row)


def _release_open_event(connection, row_id: int, remove: int | None) -> None:
    """Keep a not-yet-synced production event in step with a local change to
    its queue row, so a later retry cannot resend the old quantity.

    remove=None cancels the event; remove=N takes N off it. Only safe when
    Planner definitely refused the event (a 4xx answer). After a timeout it may
    have landed, so the local change has to wait for the retry to settle it."""
    event = connection.execute(
        """
        SELECT * FROM production_events
        WHERE target_row_id = %s AND action = 'produced'
          AND status IN ('pending', 'error')
        FOR UPDATE
        """,
        (row_id,),
    ).fetchone()
    if not event:
        return
    status = event["error_status"]
    if status is None or status in (408, 429) or not 400 <= status < 500:
        raise ValueError(
            "Planner has not confirmed this print yet. Try again once it has synced."
        )
    left = 0 if remove is None else int(event["quantity"]) - remove
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    if left > 0:
        connection.execute(
            "UPDATE production_events SET quantity = %s, updated_at = %s "
            "WHERE event_id = %s",
            (left, now, event["event_id"]),
        )
    else:
        connection.execute(
            "UPDATE production_events SET status = 'cancelled', updated_at = %s "
            "WHERE event_id = %s",
            (now, event["event_id"]),
        )


def update_printed_part(
    row_id: int,
    po_number: str,
    part_code: str,
    quantity: int,
) -> dict:
    code, qty = _part_qty(part_code, quantity)
    po = _po_number(po_number)
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        row = connection.execute(
            "SELECT status, work_date FROM printed_parts WHERE id = %s",
            (row_id,),
        ).fetchone()
        if not row or row["status"] in {"pushed", "synced"}:
            raise ValueError("Queue row was not found.")
        if row["work_date"] != current_work_date():
            raise ValueError("Archived queue rows cannot be edited.")
        if row["status"] == "error":
            # ponytail: no screen edits these rows; reject instead of rewriting
            # the pending event. Delete and reprint to correct one.
            raise ValueError("Rows waiting for Planner cannot be edited.")
        connection.execute(
            """
            UPDATE printed_parts
            SET po_number = %s, part_code = %s, quantity = %s, status = 'queued'
            WHERE id = %s
            """,
            (po, code, qty, row_id),
        )
        updated = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s",
            (row_id,),
        ).fetchone()
    return dict(updated)


def _decrement_row(connection, row: dict) -> dict | None:
    if int(row["quantity"]) <= 1:
        connection.execute("DELETE FROM printed_parts WHERE id = %s", (row["id"],))
        return None
    updated = connection.execute(
        "UPDATE printed_parts SET quantity = quantity - 1 WHERE id = %s RETURNING *",
        (row["id"],),
    ).fetchone()
    return dict(updated)


def decrement_printed_part(row_id: int) -> dict | None:
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        row = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s FOR UPDATE",
            (row_id,),
        ).fetchone()
        if not row or row["status"] in {"pushed", "synced"}:
            raise ValueError("Queue row was not found.")
        if row["work_date"] != current_work_date():
            raise ValueError("Archived queue rows cannot be edited.")
        return _decrement_row(connection, row)


def record_local_rejection(
    event_id: str,
    row_id: int,
    problem_description: str,
    disposition: str,
) -> dict | None:
    event = _event_id(event_id)
    description, selected_disposition = _qc_details(
        problem_description, disposition
    )
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        existing = connection.execute(
            "SELECT * FROM production_events WHERE event_id = %s",
            (event,),
        ).fetchone()
        if existing:
            expected = ("rejected", row_id, description, selected_disposition)
            actual = (
                existing["action"],
                existing["target_row_id"],
                existing["problem_description"],
                existing["disposition"],
            )
            if actual != expected:
                raise ValueError(
                    "event_id was already used with different production data."
                )
            row = connection.execute(
                "SELECT * FROM printed_parts WHERE id = %s AND quantity > 0",
                (row_id,),
            ).fetchone()
            return dict(row) if row else None

        row = connection.execute(
            "SELECT * FROM printed_parts WHERE id = %s FOR UPDATE",
            (row_id,),
        ).fetchone()
        if not row or row["status"] in {"pushed", "synced"}:
            raise ValueError("Queue row was not found.")
        if row["work_date"] != current_work_date():
            raise ValueError("Archived queue rows cannot be edited.")
        _release_open_event(connection, row_id, 1)
        connection.execute(
            """
            INSERT INTO production_events
                (event_id, action, po_number, so_number, part_code, quantity,
                 work_date, target_row_id, planner_plan_id, status,
                 problem_description, disposition, created_at, updated_at)
            VALUES (%s, 'rejected', %s, %s, %s, 1, %s, %s, %s, 'skipped',
                    %s, %s, %s, %s)
            """,
            (
                event,
                row["po_number"],
                row["so_number"],
                row["part_code"],
                row["work_date"],
                row_id,
                row["planner_plan_id"],
                description,
                selected_disposition,
                now,
                now,
            ),
        )
        return _decrement_row(connection, row)


