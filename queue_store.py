def list_due_production_events(
    base_seconds: int = 60, max_seconds: int = 1800
) -> list[dict]:
    """Unsynced events whose retry backoff has elapsed, oldest first. The wait
    doubles per failed attempt (60s, 2m, 4m ... capped at 30m); an event never
    tried yet waits one base interval so an in-flight request is left alone."""
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        rows = connection.execute(
            """
            SELECT * FROM production_events
            WHERE status IN ('pending', 'error')
            ORDER BY created_at, event_id
            """
        ).fetchall()
    now = datetime.now(timezone.utc)
    due = []
    for row in rows:
        wait = min(base_seconds * 2 ** min(int(row["attempts"]), 10), max_seconds)
        try:
            idle = (now - datetime.fromisoformat(row["updated_at"])).total_seconds()
        except ValueError:
            idle = wait
        if idle >= wait:
            due.append(dict(row))
    return due


def list_production_events(work_date: str | None = None) -> dict:
    """Planner sync ledger: what was sent, what Planner answered, what failed.

    'synced' means Planner accepted it; 'skipped' means Planner was already
    fulfilled and the print was kept local. Other states can be retried."""
    selected_date = _work_date(work_date)
    _ensure_schema()
    with _queue_lock, _connect() as connection:
        rows = connection.execute(
            """
            SELECT * FROM production_events
            WHERE work_date = %s AND status != 'cancelled'
            ORDER BY created_at DESC, event_id DESC
            """,
            (selected_date,),
        ).fetchall()

    items = []
    for row in rows:
        try:
            response = json.loads(row["planner_response"] or "{}")
        except json.JSONDecodeError:
            response = {}
        items.append(
            {
                "event_id": row["event_id"],
                "action": row["action"],
                "po_number": row["po_number"],
                "so_number": row["so_number"] or response.get("soNumber") or "",
                "part_code": row["part_code"],
                "quantity": row["quantity"],
                "work_date": row["work_date"],
                "status": row["status"],
                "error": row["error"],
                "attempts": row["attempts"],
                "problem_description": row["problem_description"],
                "disposition": row["disposition"],
                "created_at": row["created_at"],
                "updated_at": row["updated_at"],
                "plan_id": row["planner_plan_id"] or response.get("planId") or "",
                "plan_label": response.get("planLabel") or "",
                "production_day": response.get("productionDay"),
                "panel_total": response.get("panelTotal"),
                "allocations": response.get("allocations") or [],
                "associated": response.get("associated") or [],
            }
        )
    return {
        "date": selected_date,
        "today": current_work_date(),
        "items": items,
        "pending": sum(
            1 for item in items if item["status"] in {"pending", "error"}
        ),
    }


def list_qc_records(work_date: str | None = None) -> dict:
    ledger = list_production_events(work_date)
    items = [
        item
        for item in ledger["items"]
        if item["action"] == "rejected"
        and item["status"] in {"synced", "skipped"}
    ]
    items.reverse()
    return {
        "date": ledger["date"],
        "today": ledger["today"],
        "items": items,
    }


